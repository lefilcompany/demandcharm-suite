import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "@/lib/auth";
import { ARTIFACT_MAX_BYTES, safeFileName, type AdrStatus, type ArtifactKind } from "@/lib/artifacts";

const BUCKET = "sprint-artifacts";

export interface BoardArtifact {
  id: string;
  board_id: string;
  sprint_id: string | null;
  kind: ArtifactKind;
  title: string;
  source: "upload" | "authored";
  file_path: string | null;
  file_name: string | null;
  file_size: number | null;
  mime_type: string | null;
  content: string | null;
  is_template: boolean;
  adr_number: number | null;
  adr_status: AdrStatus | null;
  superseded_by: string | null;
  related_demand_ids: string[];
  auto_generated: boolean;
  created_by: string;
  created_at: string;
  updated_at: string;
}

const t = () => supabase.from("board_artifacts" as any) as any;

export function useBoardArtifacts(boardId: string | null | undefined) {
  const { user } = useAuth();
  return useQuery({
    queryKey: ["board-artifacts", user?.id, boardId],
    enabled: !!boardId && !!user,
    queryFn: async () => {
      const { data, error } = await t().select("*").eq("board_id", boardId).order("created_at", { ascending: false });
      if (error) throw error;
      return (data ?? []) as BoardArtifact[];
    },
  });
}

function useInvalidate() {
  const qc = useQueryClient();
  return () => qc.invalidateQueries({ queryKey: ["board-artifacts"] });
}

export interface UploadArtifactInput {
  boardId: string;
  sprintId: string | null;
  kind: ArtifactKind;
  title: string;
  file: Blob;
  fileName: string;
  isTemplate?: boolean;
  autoGenerated?: boolean;
}

export async function uploadArtifact(userId: string, i: UploadArtifactInput) {
  if (i.file.size > ARTIFACT_MAX_BYTES) throw new Error("Arquivo maior que 20 MB");
  const id = crypto.randomUUID();
  const path = `${i.boardId}/${id}/${safeFileName(i.fileName)}`;
  const up = await supabase.storage.from(BUCKET).upload(path, i.file, { contentType: i.file.type || undefined });
  if (up.error) throw up.error;
  const { error } = await t().insert({
    id, board_id: i.boardId, sprint_id: i.sprintId, kind: i.kind, title: i.title.trim() || i.fileName,
    source: "upload", file_path: path, file_name: i.fileName, file_size: i.file.size, mime_type: i.file.type || null,
    is_template: !!i.isTemplate, auto_generated: !!i.autoGenerated, created_by: userId,
  });
  if (error) {
    await supabase.storage.from(BUCKET).remove([path]);
    throw error;
  }
  return id;
}

export function useUploadArtifact() {
  const { user } = useAuth();
  const inv = useInvalidate();
  return useMutation({
    mutationFn: (i: UploadArtifactInput) => uploadArtifact(user!.id, i),
    onSuccess: inv,
  });
}

export interface SaveAuthoredInput {
  id?: string;
  boardId: string;
  sprintId: string | null;
  kind: ArtifactKind;
  title: string;
  content: string;
  isTemplate?: boolean;
  adrStatus?: AdrStatus | null;
  relatedDemandIds?: string[];
  supersedes?: string | null;
}

export function useSaveAuthoredArtifact() {
  const { user } = useAuth();
  const inv = useInvalidate();
  return useMutation({
    mutationFn: async (i: SaveAuthoredInput) => {
      const row: any = {
        sprint_id: i.sprintId, kind: i.kind, title: i.title.trim(), content: i.content,
        is_template: !!i.isTemplate, related_demand_ids: i.relatedDemandIds ?? [],
        ...(i.kind === "adr" && !i.isTemplate ? { adr_status: i.adrStatus ?? "proposed" } : {}),
      };
      if (i.id) {
        const { error } = await t().update(row).eq("id", i.id);
        if (error) throw error;
        return i.id;
      }
      const { data, error } = await t()
        .insert({ ...row, board_id: i.boardId, source: "authored", created_by: user!.id })
        .select("id").single();
      if (error) throw error;
      if (i.supersedes) {
        const r = await t().update({ adr_status: "superseded", superseded_by: data.id }).eq("id", i.supersedes);
        if (r.error) throw r.error;
      }
      return data.id as string;
    },
    onSuccess: inv,
  });
}

export function useUpdateArtifactMeta() {
  const inv = useInvalidate();
  return useMutation({
    mutationFn: async ({ id, ...patch }: { id: string; sprint_id?: string | null; adr_status?: AdrStatus; is_template?: boolean }) => {
      const { error } = await t().update(patch).eq("id", id);
      if (error) throw error;
    },
    onSuccess: inv,
  });
}

export function useDeleteArtifact() {
  const inv = useInvalidate();
  return useMutation({
    mutationFn: async (a: BoardArtifact) => {
      const { error } = await t().delete().eq("id", a.id);
      if (error) throw error;
      if (a.file_path) await supabase.storage.from(BUCKET).remove([a.file_path]);
    },
    onSuccess: inv,
  });
}

export async function getArtifactUrl(a: BoardArtifact, download = false) {
  if (!a.file_path) return null;
  const { data, error } = await supabase.storage.from(BUCKET)
    .createSignedUrl(a.file_path, 600, download ? { download: a.file_name ?? true } : undefined);
  if (error) throw error;
  return data.signedUrl;
}
